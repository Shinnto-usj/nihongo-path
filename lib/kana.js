export const kana = groups.flatMap(([row, entries], groupIndex) => entries.map(([hiragana, katakana, romaji, variants = []]) => ({
  id: `kana-${hiragana}`,
  hiragana, katakana, romaji, row,
  variants,
  basic: groupIndex < 10,
  kind: groupIndex < 10 ? 'basic' : groupIndex < 14 ? 'voiced' : groupIndex === 14 ? 'semi-voiced' : 'contracted',
  note: notes[hiragana] || (groupIndex >= 15 ? '后面的 ゃ・ゅ・ょ 要写小；整个组合通常读一拍。' : ''),
})));

